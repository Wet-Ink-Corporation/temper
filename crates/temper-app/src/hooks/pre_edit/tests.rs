#[test]
fn a_member_gaining_lints_workspace_true_is_allowed_without_a_prompt() {
    let ws = Ws::new(files());
    let moved = MEMBER.replace("[lints]\nworkspace = true\n\n", "").replace(
        "publish.workspace = true\n",
        "publish.workspace = true\nlints.workspace = true\n",
    );

    let res = ws.edit(
        "crates/legacy/Cargo.toml",
        "[dependencies]\n",
        "[lints]\nworkspace = true\n\n[dependencies]\n",
    );
    let inline = ws.edit(
        "crates/legacy/Cargo.toml",
        "[package]\n",
        "lints.workspace = true\n\n[package]\n",
    );
    let removed = ws.edit(
        "crates/ledger-domain/Cargo.toml",
        "[lints]\nworkspace = true\n",
        "",
    );
    let moved = ws.write("crates/ledger-domain/Cargo.toml", &moved);

    assert_eq!(decision(&res), "none", "{}", reason(&res));
    assert_eq!(
        decision(&inline),
        "none",
        "a top-level dotted key is the same table: {}",
        reason(&inline)
    );
    assert_eq!(
        decision(&removed),
        "deny",
        "removing inheritance from a member that had it: {}",
        reason(&removed)
    );
    assert_eq!(
        decision(&moved),
        "deny",
        "`lints.workspace` under [package] is `package.lints`, which Cargo ignores: {}",
        reason(&moved)
    );
}

