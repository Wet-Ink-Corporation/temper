#[test]
fn non_caret_requirements_get_an_arc_12_advisory() {
    let ws = Ws::new(files());
    let req = |req: &str| {
        ws.edit(
            "Cargo.toml",
            "thiserror = \"2\"",
            &format!("thiserror = \"{req}\""),
        )
    };

    let res = req("=2.0.12");
    let flagged = ["~2.0", ">=2", ">=2, <3", "*", "2.0.12", "^2"]
        .map(|r| (r, reason(&req(r)).contains("ARC-12")));

    assert_eq!(decision(&res), "context");
    assert!(
        reason(&res).contains("ARC-12 Cargo.toml: `thiserror = \"=2.0.12\"` is an exact `=` pin")
    );
    assert_eq!(
        flagged,
        [
            ("~2.0", true),
            (">=2", true),
            (">=2, <3", true),
            ("*", true),
            ("2.0.12", false),
            ("^2", false),
        ]
    );
}

