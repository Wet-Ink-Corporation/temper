const LIB_RS: &str = "//! Domain.\n\n/// One.\n#[must_use]\npub fn one() -> u8 {\n    1\n}\n\n#[cfg(test)]\nmod tests {\n    use super::one;\n\n    #[test]\n    fn is_one() {\n        assert_eq!(one(), 1);\n    }\n}\n";

fn no_lints() -> String {
    MEMBER.replace("[lints]\nworkspace = true\n\n", "")
}

fn own_lints() -> String {
    no_lints().replace(
        "[dependencies]",
        "[lints.rust]\nunsafe_code = \"deny\"\n\n[lints.clippy]\nundocumented_unsafe_blocks = \"deny\"\n\n[dependencies]",
    )
}

/// `hooks.test.mjs`'s `before()` tree, at `/ws`.
fn files() -> FakeFiles {
    let profiled = MEMBER.replace("ledger-domain", "profiled").replace(
        "[dependencies]",
        "[profile.dev]\nopt-level = 1\n\n[dependencies]",
    );
    FakeFiles::new(Posix)
        .with_file("/ws/Cargo.toml", ROOT)
        .with_file(
            "/ws/Cargo.lock",
            "# This file is automatically @generated by Cargo.\nversion = 4\n",
        )
        .with_file("/ws/crates/ledger-domain/Cargo.toml", MEMBER)
        .with_file("/ws/crates/ledger-domain/src/lib.rs", LIB_RS)
        .with_file("/ws/crates/profiled/Cargo.toml", &profiled)
        .with_file("/ws/crates/profiled/src/lib.rs", "//! Profiled.\n")
        .with_file(
            "/ws/.claude/temper.json",
            r#"{"manifests":{"ownLints":["crates/foo-sys"]}}"#,
        )
        .with_file(
            "/ws/crates/legacy/Cargo.toml",
            &no_lints().replace("ledger-domain", "legacy"),
        )
        .with_file("/ws/crates/legacy/src/lib.rs", "//! Legacy.\n")
}

/// The workspace, a scanner, and the hook run on it.
struct Ws {
    ports: FakePorts,
    env: RunEnv,
    scanner: Scanner,
}

impl Ws {
    fn new(files: FakeFiles) -> Self {
        Self {
            ports: FakePorts::new(files),
            env: RunEnv::at("/ws", Posix),
            scanner: Scanner::new().expect("every built-in pattern compiles"),
        }
    }

    fn run(&self, event: HookEvent, json: &str) -> Result<HookOutcome, HookError> {
        let input = parsed(json);
        let call = crate::hooks::HookCall {
            ports: &self.ports,
            env: &self.env,
            input: &input,
        };
        crate::hooks::run(&call, &self.scanner, event)
    }

    fn hook(&self, json: &str) -> Result<HookOutcome, HookError> {
        self.run(HookEvent::PreEdit, json)
    }

    /// 1.x `preEdit(input(tool, rel, toolInput))`: a preloaded agent, which skips the skill gate.
    fn tool(&self, tool: &str, rel: &str, fields: &str) -> HookOutcome {
        let json = format!(
            r#"{{"tool_name":"{tool}","cwd":"/ws","session_id":"hooks-test","agent_type":"temper:rust-implementer","tool_input":{{"file_path":"/ws/{rel}"{fields}}}}}"#
        );
        self.hook(&json).expect("the handler answers")
    }

    fn write(&self, rel: &str, content: &str) -> HookOutcome {
        self.tool("Write", rel, &format!(r#","content":{}"#, quoted(content)))
    }

    fn edit(&self, rel: &str, old: &str, new: &str) -> HookOutcome {
        let fields = format!(
            r#","old_string":{},"new_string":{}"#,
            quoted(old),
            quoted(new)
        );
        self.tool("Edit", rel, &fields)
    }
}

fn parsed(json: &str) -> HookInput {
    HookInput::parse(json).expect("the test's input is JSON")
}

/// `text` as a JSON string.
fn quoted(text: &str) -> String {
    temper_domain::JsValue::String(text.to_owned()).to_json()
}

/// `hooks.test.mjs`'s `decision(res)`.
fn decision(outcome: &HookOutcome) -> &'static str {
    match outcome {
        HookOutcome::Deny { .. } => "deny",
        HookOutcome::Ask { .. } => "ask",
        HookOutcome::Context { .. } | HookOutcome::ContextWithNotice { .. } => "context",
        HookOutcome::Pass => "none",
        HookOutcome::Notice { .. } => "notice",
        HookOutcome::Block { .. } => "block",
    }
}

/// `hooks.test.mjs`'s `reason(res)`: the decision's reason, a newline, and the context.
fn reason(outcome: &HookOutcome) -> String {
    match outcome {
        HookOutcome::Deny { reason, context } | HookOutcome::Ask { reason, context } => {
            format!("{reason}\n{}", context.as_deref().unwrap_or(""))
        }
        HookOutcome::Context { text, .. } | HookOutcome::ContextWithNotice { text, .. } => {
            format!("\n{text}")
        }
        HookOutcome::Block { reason } => format!("{reason}\n"),
        HookOutcome::Pass | HookOutcome::Notice { .. } => "\n".to_owned(),
    }
}

/// Does `text` hold `parts` in order, the way a regex joins them with `[\s\S]*`?
fn in_order(text: &str, parts: &[&str]) -> bool {
    parts
        .iter()
        .try_fold(text, |rest, part| {
            rest.find(part)
                .map(|at| rest.get(at.saturating_add(part.len())..).unwrap_or(""))
        })
        .is_some()
}

/// Does one line of `text` hold `parts` in order, the way a regex joins them with `.*`?
fn on_one_line(text: &str, parts: &[&str]) -> bool {
    text.lines().any(|line| in_order(line, parts))
}

