#[test]
fn manifests_own_lints_a_listed_member_may_carry_its_own_lints_table_and_changing_it_asks() {
    let ws = Ws::new(files());

    let own = ws.write(
        "crates/foo-sys/Cargo.toml",
        &own_lints().replace("ledger-domain", "foo-sys"),
    );
    let none = ws.write(
        "crates/foo-sys/Cargo.toml",
        &no_lints().replace("ledger-domain", "foo-sys"),
    );
    let unlisted = ws.write(
        "crates/bar-sys/Cargo.toml",
        &own_lints().replace("ledger-domain", "bar-sys"),
    );

    assert_eq!(decision(&own), "ask", "{}", reason(&own));
    assert!(reason(&own).contains("[lints]/[profile] sections change (H-05)"));
    assert_eq!(decision(&none), "deny");
    assert!(reason(&none).contains("listed in manifests.ownLints but has no `[lints]` table"));
    assert_eq!(decision(&unlisted), "deny");
    assert!(reason(&unlisted).contains("manifests.ownLints"));
}

