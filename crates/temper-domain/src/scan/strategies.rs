/// Sources built from the tokens the lexer branches on and the rule predicates and finders read,
/// mixed with arbitrary chars, so the scan properties reach every predicate and resume path.
pub(super) fn token_soup() -> impl Strategy<Value = String> {
    let token = prop_oneof![
        select(TOKENS).prop_map(str::to_owned),
        Just("\"".to_owned()),
        Just("'".to_owned()),
        Just("r#\"".to_owned()),
        Just("\"#".to_owned()),
        Just("br\"".to_owned()),
        Just("/*".to_owned()),
        Just("*/".to_owned()),
        Just("//".to_owned()),
        Just("\n".to_owned()),
        Just("\r".to_owned()),
        Just("\\".to_owned()),
        Just("#".to_owned()),
        Just("a".to_owned()),
        Just(" ".to_owned()),
        any::<char>().prop_map(String::from),
    ];
    vec(token, 0..64).prop_map(|tokens| tokens.concat())
}
