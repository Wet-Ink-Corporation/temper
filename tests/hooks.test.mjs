test('a rust-version bump asks (H-16); unrelated root edits do not', () => {
  const res = editIn('Cargo.toml', 'rust-version = "1.96"', 'rust-version = "1.97"');
  assert.equal(decision(res), 'ask');
  assert.match(reason(res), /`workspace\.package\.rust-version` changes \("1\.96" -> "1\.97"\).*H-16/);
  const other = editIn('Cargo.toml', '# Workspace manifest (from the temper template).', '# Workspace manifest.');
  assert.equal(decision(other), 'none', reason(other));
  const defaults = editIn('crates/ledger-domain/Cargo.toml', '[dependencies]\n', '[features]\ndefault = ["std"]\nstd = []\n\n[dependencies]\n');
  assert.match(reason(defaults), /`features\.default`.*H-16/);
});

test('non-caret requirements get an ARC-12 advisory', () => {
  const res = editIn('Cargo.toml', 'thiserror = "2"', 'thiserror = "=2.0.12"');
  assert.equal(decision(res), 'context');
  assert.match(reason(res), /ARC-12 Cargo\.toml: `thiserror = "=2\.0\.12"` is an exact `=` pin/);
  for (const [req, ok] of [['~2.0', false], ['>=2', false], ['>=2, <3', false], ['*', false], ['2.0.12', true], ['^2', true]]) {
    const r = editIn('Cargo.toml', 'thiserror = "2"', `thiserror = "${req}"`);
    assert.equal(/ARC-12/.test(reason(r)), !ok, req);
  }
});

