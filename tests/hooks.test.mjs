test('gate manifests step with git: only problems new since the base fail', { skip: (!cargo || !git) && 'cargo or git not installed' }, () => {
  const repo = fs.mkdtempSync(path.join(os.tmpdir(), 'temper-ratchet-'));
  const put = (rel, text) => { const p = path.join(repo, ...rel.split('/')); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text); };
  const g = (...args) => spawnSync('git', args, { cwd: repo, encoding: 'utf8' });
  try {
    put('Cargo.toml', ROOT.replace('[profile.release]\nlto = "thin"\n', ''));
    put('crates/good/Cargo.toml', MEMBER.replace('ledger-domain', 'good'));
    put('crates/good/src/lib.rs', '//! Good.\n');
    put('crates/legacy/Cargo.toml', NO_LINTS.replace('ledger-domain', 'legacy'));
    put('crates/legacy/src/lib.rs', '//! Legacy.\n');
    g('init', '-q');
    g('add', '-A');
    g('-c', 'user.email=t@example.com', '-c', 'user.name=t', 'commit', '-qm', 'base');
    const base = g('rev-parse', 'HEAD').stdout.trim();
    const proj = discover(repo);
    const legacy = checkManifests(proj, base);
    assert.equal(legacy.ok, true, legacy.summary);
    assert.match(legacy.summary, /older problem\(s\) not introduced since the base \(advisory\): MOD-09 crates\/legacy\/Cargo\.toml/);
    // an edit to the legacy member that keeps the old problem stays green
    put('crates/legacy/Cargo.toml', NO_LINTS.replace('ledger-domain', 'legacy').replace('Pure account rules', 'Legacy'));
    assert.equal(checkManifests(proj, base).ok, true);
    // a new untracked member without inheritance fails
    put('crates/fresh/Cargo.toml', NO_LINTS.replace('ledger-domain', 'fresh'));
    put('crates/fresh/src/lib.rs', '//! Fresh.\n');
    const fresh = checkManifests(proj, base);
    assert.equal(fresh.ok, false);
    assert.match(fresh.summary, /MOD-09 crates\/fresh\/Cargo\.toml/);
    assert.doesNotMatch(fresh.summary.split('\n')[0], /legacy/);
    fs.rmSync(path.join(repo, 'crates', 'fresh'), { recursive: true, force: true });
    // removing inheritance from a member that had it fails; a new profile fails
    put('crates/good/Cargo.toml', NO_LINTS.replace('ledger-domain', 'good'));
    assert.match(checkManifests(proj, base).summary, /MOD-09 crates\/good\/Cargo\.toml/);
    put('crates/good/Cargo.toml', MEMBER.replace('ledger-domain', 'good').replace('[dependencies]', '[profile.dev]\nopt-level = 1\n\n[dependencies]'));
    assert.match(checkManifests(proj, base).summary, /PERF-09 crates\/good\/Cargo\.toml/);
    // an ownLints member with its own full table passes
    put('.claude/temper.json', JSON.stringify({ manifests: { ownLints: ['crates/good'] } }));
    put('crates/good/Cargo.toml', OWN_LINTS.replace('ledger-domain', 'good'));
    const own = checkManifests(discover(repo), base);
    assert.equal(own.ok, true, own.summary);
  } finally {
    fs.rmSync(repo, { recursive: true, force: true });
  }
});

