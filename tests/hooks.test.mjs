// Hook handlers called directly on throwaway workspaces (no git, so the
// project root is the outermost Cargo.toml directory).
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { preEdit, preBash, lintConfigChanged } from '../scripts/lib/hooks.mjs';
import { checkManifests, checkManifestsToml, runGate, renderGate } from '../scripts/lib/gate.mjs';
import { discover } from '../scripts/lib/project.mjs';

const ROOT = `# Workspace manifest (from the temper template).
[workspace]
resolver = "3"
members = ["crates/*"]
exclude = ["crates/scratch", "./tools/gen/"]

[workspace.package]
edition = "2024"
rust-version = "1.96"
version = "0.1.0"
publish = false

[workspace.dependencies]
thiserror = "2"

[workspace.lints.rust]
unsafe_code = "forbid"

[workspace.lints.clippy]
unwrap_used = "deny"

[profile.release]
lto = "thin"
`;

const MEMBER = `[package]
name = "ledger-domain"
description = "Pure account rules"
edition.workspace = true
version.workspace = true
rust-version.workspace = true
publish.workspace = true

[lints]
workspace = true

[dependencies]
thiserror = { workspace = true }
`;

const NO_LINTS = MEMBER.replace('[lints]\nworkspace = true\n\n', '');
const OWN_LINTS = NO_LINTS.replace('[dependencies]', '[lints.rust]\nunsafe_code = "deny"\n\n[lints.clippy]\nundocumented_unsafe_blocks = "deny"\n\n[dependencies]');
const LIB_RS = '//! Domain.\n\n/// One.\n#[must_use]\npub fn one() -> u8 {\n    1\n}\n\n#[cfg(test)]\nmod tests {\n    use super::one;\n\n    #[test]\n    fn is_one() {\n        assert_eq!(one(), 1);\n    }\n}\n';

let ws;
const file = (rel) => path.join(ws, ...rel.split('/'));
const write = (rel, text) => { fs.mkdirSync(path.dirname(file(rel)), { recursive: true }); fs.writeFileSync(file(rel), text); };

before(() => {
  ws = fs.mkdtempSync(path.join(os.tmpdir(), 'temper-hooks-'));
  write('Cargo.toml', ROOT);
  write('Cargo.lock', '# This file is automatically @generated by Cargo.\nversion = 4\n');
  write('crates/ledger-domain/Cargo.toml', MEMBER);
  write('crates/ledger-domain/src/lib.rs', LIB_RS);
  write('crates/profiled/Cargo.toml', MEMBER.replace('ledger-domain', 'profiled').replace('[dependencies]', '[profile.dev]\nopt-level = 1\n\n[dependencies]'));
  write('crates/profiled/src/lib.rs', '//! Profiled.\n');
  write('.claude/temper.json', JSON.stringify({ manifests: { ownLints: ['crates/foo-sys'] } }));
  write('crates/legacy/Cargo.toml', NO_LINTS.replace('ledger-domain', 'legacy'));
  write('crates/legacy/src/lib.rs', '//! Legacy.\n');
});

after(() => { fs.rmSync(ws, { recursive: true, force: true }); });

// A preloaded agent type skips the skill gate; tests/handlers.test.mjs covers the gate itself.
const input = (tool, rel, toolInput) => ({
  tool_name: tool, cwd: ws, session_id: 'hooks-test', agent_type: 'temper:rust-implementer',
  tool_input: { file_path: file(rel), ...toolInput },
});
const writeTo = (rel, content) => preEdit(input('Write', rel, { content }));
const editIn = (rel, oldString, newString) => preEdit(input('Edit', rel, { old_string: oldString, new_string: newString }));
const decision = (res) => res.json?.hookSpecificOutput?.permissionDecision ?? (res.json?.hookSpecificOutput?.additionalContext ? 'context' : 'none');
const reason = (res) => `${res.json?.hookSpecificOutput?.permissionDecisionReason ?? ''}\n${res.json?.hookSpecificOutput?.additionalContext ?? ''}`;
const bash = (command) => preBash({ tool_name: 'Bash', cwd: ws, session_id: 'hooks-test', tool_input: { command } });

test('the throwaway workspace is discovered without git', () => {
  const proj = discover(ws);
  assert.equal(path.resolve(proj.root), path.resolve(ws));
  assert.equal(proj.gitRoot, null);
});

test('new member crate without [lints] workspace = true is denied (MOD-09)', () => {
  const res = writeTo('crates/ledger-extra/Cargo.toml', NO_LINTS.replace('ledger-domain', 'ledger-extra'));
  assert.equal(decision(res), 'deny');
  assert.match(reason(res), /MOD-09 crates\/ledger-extra\/Cargo\.toml/);
  assert.match(reason(res), /`workspace = true`/);
});

test('new member crate with lint inheritance asks as a crate boundary (H-16), not as a lint change', () => {
  const res = writeTo('crates/ledger-extra/Cargo.toml', MEMBER.replace('ledger-domain', 'ledger-extra'));
  assert.equal(decision(res), 'ask');
  assert.match(reason(res), /new crate `ledger-extra`.*H-16/);
  assert.doesNotMatch(reason(res), /H-05/);
  assert.doesNotMatch(reason(res), /rust-version|edition/); // inherited keys are benign in a new manifest
});

test('an excluded crate is not a member', () => {
  const res = writeTo('crates/scratch/Cargo.toml', NO_LINTS.replace('ledger-domain', 'scratch'));
  assert.notEqual(decision(res), 'deny');
});

test('a member gaining [lints] workspace = true is allowed without a prompt', () => {
  const res = editIn('crates/legacy/Cargo.toml', '[dependencies]\n', '[lints]\nworkspace = true\n\n[dependencies]\n');
  assert.equal(decision(res), 'none', reason(res));
  // a top-level dotted key is the same table
  const inline = editIn('crates/legacy/Cargo.toml', '[package]\n', 'lints.workspace = true\n\n[package]\n');
  assert.equal(decision(inline), 'none', reason(inline));
  // removing inheritance from a member that had it is denied
  const removed = editIn('crates/ledger-domain/Cargo.toml', '[lints]\nworkspace = true\n', '');
  assert.equal(decision(removed), 'deny', reason(removed));
  // `lints.workspace` under [package] is `package.lints`, which Cargo ignores
  const moved = preEdit(input('Write', 'crates/ledger-domain/Cargo.toml', { content: MEMBER.replace('[lints]\nworkspace = true\n\n', '').replace('publish.workspace = true\n', 'publish.workspace = true\nlints.workspace = true\n') }));
  assert.equal(decision(moved), 'deny', reason(moved));
});

test('ratchet: a legacy member without inheritance or with a profile only advises', () => {
  const res = editIn('crates/legacy/Cargo.toml', 'description = "Pure account rules"', 'description = "Legacy rules"');
  assert.equal(decision(res), 'context', reason(res));
  assert.match(reason(res), /MOD-09 crates\/legacy\/Cargo\.toml \(already the case before this edit\)/);
  const prof = editIn('crates/profiled/Cargo.toml', 'description = "Pure account rules"', 'description = "Profiled"');
  assert.equal(decision(prof), 'context', reason(prof));
  assert.match(reason(prof), /PERF-09 crates\/profiled\/Cargo\.toml \(already the case/);
});

test('manifests.ownLints: a listed member may carry its own [lints] table, and changing it asks (H-05)', () => {
  const own = writeTo('crates/foo-sys/Cargo.toml', OWN_LINTS.replace('ledger-domain', 'foo-sys'));
  assert.equal(decision(own), 'ask', reason(own));
  assert.match(reason(own), /\[lints\]\/\[profile\] sections change \(H-05\)/);
  const none = writeTo('crates/foo-sys/Cargo.toml', NO_LINTS.replace('ledger-domain', 'foo-sys'));
  assert.equal(decision(none), 'deny');
  assert.match(reason(none), /listed in manifests\.ownLints but has no `\[lints\]` table/);
  const unlisted = writeTo('crates/bar-sys/Cargo.toml', OWN_LINTS.replace('ledger-domain', 'bar-sys'));
  assert.equal(decision(unlisted), 'deny');
  assert.match(reason(unlisted), /manifests\.ownLints/);
});

test('a member that overrides lints is a lint-config change (H-05)', () => {
  const res = editIn('crates/ledger-domain/Cargo.toml', '[lints]\nworkspace = true\n', '[lints.clippy]\nunwrap_used = "allow"\n');
  assert.equal(decision(res), 'deny'); // and it no longer inherits
  const root = editIn('Cargo.toml', 'unwrap_used = "deny"', 'unwrap_used = "warn"');
  assert.equal(decision(root), 'ask');
  assert.match(reason(root), /\[lints\]\/\[profile\] sections change \(H-05\)/);
});

test('[profile] in a member manifest is denied (PERF-09); in the root it asks', () => {
  const res = editIn('crates/ledger-domain/Cargo.toml', '[dependencies]\n', '[profile.release]\nopt-level = 3\n\n[dependencies]\n');
  assert.equal(decision(res), 'deny');
  assert.match(reason(res), /PERF-09/);
  const root = editIn('Cargo.toml', 'lto = "thin"', 'lto = "fat"');
  assert.equal(decision(root), 'ask');
  assert.doesNotMatch(reason(root), /PERF-09/);
});

test('test = false on a target asks (H-12)', () => {
  const res = editIn('crates/ledger-domain/Cargo.toml', '[dependencies]\n', '[lib]\ntest = false\ndoctest = false\n\n[dependencies]\n');
  assert.equal(decision(res), 'ask');
  assert.match(reason(res), /`\[lib\] test` changes \(unset -> false\); this switch can stop tests/);
  assert.match(reason(res), /`\[lib\] doctest` changes/);
  const harness = editIn('crates/ledger-domain/Cargo.toml', '[dependencies]\n', '[[test]]\nname = "it"\nharness = false\n\n[dependencies]\n');
  assert.match(reason(harness), /`\[\[test\]\] it harness`.*H-12/);
  const bench = editIn('crates/ledger-domain/Cargo.toml', '[dependencies]\n', '[[bench]]\nname = "decide"\nharness = false\n\n[dependencies]\n');
  assert.equal(decision(bench), 'none', reason(bench)); // divan and criterion need it
  const auto = editIn('crates/ledger-domain/Cargo.toml', 'publish.workspace = true\n', 'publish.workspace = true\nautotests = false\n');
  assert.match(reason(auto), /`package\.autotests`.*H-12/);
});

